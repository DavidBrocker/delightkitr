#!/usr/bin/env python3
"""Minimal roxygen-to-Rd generator, used only because roxygen2 is not installed.
Handles the tags this package uses: title/description/details paragraphs,
@param, @inheritParams, @return, @examples, @export. Re-run devtools::document()
when roxygen2 is available; it should produce equivalent files.

    python3 data-raw/roxy-lite.py R/file1.R R/file2.R ...
"""
import re, sys, pathlib

def esc(t):
    t = t.replace('%', r'\%')
    t = re.sub(r'\[([A-Za-z_.][A-Za-z0-9_.]*)\(\)\]', lambda m: r'\code{\link[=%s]{%s()}}' % (m[1], m[1]), t)
    t = re.sub(r'`([^`]+)`', lambda m: r'\code{%s}' % m[1].replace('\\', r'\\'), t)
    t = re.sub(r'\*([A-Za-z][^*]*)\*', lambda m: r'\emph{%s}' % m[1], t)
    return t

def split_args(s):
    out, depth, cur, q = [], 0, '', None
    for ch in s:
        if q:
            cur += ch
            if ch == q: q = None
            continue
        if ch in '"\'': q = ch; cur += ch; continue
        if ch in '([{': depth += 1
        if ch in ')]}': depth -= 1
        if ch == ',' and depth == 0: out.append(cur.strip()); cur = ''
        else: cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

def parse(path):
    lines = pathlib.Path(path).read_text().split('\n')
    blocks, i = [], 0
    while i < len(lines):
        if lines[i].startswith("#'"):
            j = i
            while j < len(lines) and lines[j].startswith("#'"): j += 1
            body = [l[2:].lstrip(' ') if l[2:3] == ' ' else l[2:] for l in lines[i:j]]
            k = j
            m = re.match(r'([A-Za-z_.][A-Za-z0-9_.]*)\s*<-\s*function\(', lines[k]) if k < len(lines) else None
            if m:
                # collect signature up to the matching close paren
                text = '\n'.join(lines[k:])
                start = text.index('function(') + len('function(')
                depth, q, e = 1, None, start
                while depth:
                    ch = text[e]
                    if q:
                        if ch == q: q = None
                    elif ch in '"\'': q = ch
                    elif ch == '(': depth += 1
                    elif ch == ')': depth -= 1
                    e += 1
                sig = ' '.join(text[start:e - 1].split())
                blocks.append((m[1], body, split_args(sig)))
            i = j
        else:
            i += 1
    return blocks

def parse_body(body):
    paras, tags, cur = [], [], None
    text = []
    for l in body:
        if l.startswith('@'):
            m = re.match(r'@(\w+)\s*(.*)', l)
            cur = [m[1], m[2]]; tags.append(cur)
        elif cur is not None:
            cur[1] += '\n' + l
        else:
            text.append(l)
    cur_p = []
    for l in text + ['']:
        if l.strip() == '':
            if cur_p: paras.append(' '.join(x.strip() for x in cur_p)); cur_p = []
        else: cur_p.append(l)
    return paras, tags

registry = {}
files = sys.argv[1:]
parsed = []
for f in files:
    for name, body, args in parse(f):
        paras, tags = parse_body(body)
        if not paras or any(t[0] == 'noRd' for t in tags):
            continue
        params = {}
        for t, v in tags:
            if t == 'param':
                key, _, desc = v.partition(' ')
                params[key.replace(',', ', ').replace(',  ', ', ')] = ' '.join(desc.split())
        registry[name] = params
        parsed.append((f, name, paras, tags, args, params))

# pull in params already documented elsewhere (for @inheritParams across files)
for f in pathlib.Path('R').glob('*.R'):
    for name, body, args in parse(str(f)):
        if name in registry: continue
        paras, tags = parse_body(body)
        params = {}
        for t, v in tags:
            if t == 'param':
                key, _, desc = v.partition(' ')
                params[key.replace(',', ', ')] = ' '.join(desc.split())
        registry[name] = params

def argnames(args): return [a.split('=')[0].strip() for a in args]

for f, name, paras, tags, args, params in parsed:
    names = argnames(args)
    for t, v in tags:
        if t == 'inheritParams':
            src = registry.get(v.strip(), {})
            for key, desc in src.items():
                ks = [k.strip() for k in key.split(',')]
                if any(k in names for k in ks) and not any(k in names for k in [x.strip() for p in params for x in p.split(',')] if k in ks):
                    if key not in params and all(k in names for k in ks):
                        params[key] = desc
    title = paras[0].rstrip('.') if not paras[0].endswith('.') else paras[0][:-1]
    desc = paras[1] if len(paras) > 1 else paras[0]
    details = paras[2:]
    ret = next((v for t, v in tags if t == 'return'), None)
    ex = next((v for t, v in tags if t == 'examples'), None)
    out = ['% Generated by roxygen2: do not edit by hand',
           '%% Please edit documentation in %s' % f,
           r'\name{%s}' % name, r'\alias{%s}' % name, r'\title{%s}' % esc(title)]
    one = '%s(%s)' % (name, ', '.join(args))
    if len(one) <= 80: out.append('\\usage{\n%s\n}' % one)
    else: out.append('\\usage{\n%s(\n  %s\n)\n}' % (name, ',\n  '.join(args)))
    items = []
    covered = set()
    for key, d in params.items():
        ks = [k.strip() for k in key.split(',')]
        if any(k in names for k in ks):
            items.append('\\item{%s}{%s}' % (key if len(ks) == 1 else ', '.join(ks), esc(d)))
            covered.update(ks)
    missing = [n for n in names if n not in covered]
    if missing: sys.exit('%s: undocumented args %s' % (name, missing))
    if items: out.append('\\arguments{\n%s\n}' % '\n\n'.join(items))
    if ret: out.append('\\value{\n%s\n}' % esc(' '.join(ret.split())))
    out.append('\\description{\n%s\n}' % esc(desc))
    if details: out.append('\\details{\n%s\n}' % '\n\n'.join(esc(d) for d in details))
    if ex: out.append('\\examples{\n%s\n}' % ex.replace('%', r'\%').strip('\n'))
    pathlib.Path('man/%s.Rd' % name).write_text('\n'.join(out) + '\n')
    print('wrote man/%s.Rd' % name)
